import { createClient } from '@supabase/supabase-js'
import { config } from 'dotenv'
import sharp from 'sharp'
import { mkdir, writeFile } from 'node:fs/promises'

config({ path: '.env.migrate.local' })

const requiredEnv = [
  'OLD_SUPABASE_URL',
  'OLD_SUPABASE_SERVICE_ROLE_KEY',
  'NEW_SUPABASE_URL',
  'NEW_SUPABASE_SERVICE_ROLE_KEY',
]

for (const key of requiredEnv) {
  if (!process.env[key]) {
    console.error(`Missing required env var: ${key}`)
    process.exit(1)
  }
}

const bucket = process.env.SUPABASE_BUCKET || 'happycheese-images'
const cacheControl = '31536000'
const applyDbUpdates = process.env.APPLY_DB_UPDATES === 'true'

function normalizeSupabaseUrl(url) {
  return url.replace(/\/rest\/v1\/?$/, '').replace(/\/+$/, '')
}

const oldClient = createClient(
  normalizeSupabaseUrl(process.env.OLD_SUPABASE_URL),
  process.env.OLD_SUPABASE_SERVICE_ROLE_KEY,
  {
    auth: { autoRefreshToken: false, persistSession: false },
    db: { schema: 'happycheese' },
  }
)

const newClient = createClient(
  normalizeSupabaseUrl(process.env.NEW_SUPABASE_URL),
  process.env.NEW_SUPABASE_SERVICE_ROLE_KEY,
  {
    auth: { autoRefreshToken: false, persistSession: false },
    db: { schema: 'happycheese' },
  }
)

function parsePublicStorageUrl(url) {
  const marker = '/storage/v1/object/public/'
  const index = url.indexOf(marker)
  if (index === -1) return null

  const objectPart = decodeURIComponent(url.slice(index + marker.length))
  const slashIndex = objectPart.indexOf('/')
  if (slashIndex === -1) return null

  return {
    bucket: objectPart.slice(0, slashIndex),
    path: objectPart.slice(slashIndex + 1),
  }
}

async function downloadFlavorImage(imageUrl) {
  const parsed = parsePublicStorageUrl(imageUrl)

  if (parsed) {
    const { data, error } = await oldClient.storage
      .from(parsed.bucket)
      .download(parsed.path)

    if (error) {
      throw new Error(`Storage download failed for ${parsed.path}: ${error.message}`)
    }

    return Buffer.from(await data.arrayBuffer())
  }

  const response = await fetch(imageUrl)
  if (!response.ok) {
    throw new Error(`HTTP download failed for ${imageUrl}: ${response.status}`)
  }

  return Buffer.from(await response.arrayBuffer())
}

async function createVariants(buffer) {
  const base = sharp(buffer, { failOn: 'none' }).rotate()

  const full = await base
    .clone()
    .resize({ width: 1600, height: 1200, fit: 'inside', withoutEnlargement: true })
    .webp({ quality: 82 })
    .toBuffer()

  const thumb = await base
    .clone()
    .resize({ width: 640, height: 640, fit: 'cover', withoutEnlargement: true })
    .webp({ quality: 76 })
    .toBuffer()

  return { full, thumb }
}

async function upload(path, buffer) {
  const { data, error } = await newClient.storage
    .from(bucket)
    .upload(path, buffer, {
      contentType: 'image/webp',
      cacheControl,
      upsert: true,
    })

  if (error) {
    throw new Error(`Upload failed for ${path}: ${error.message}`)
  }

  const { data: urlData } = newClient.storage
    .from(bucket)
    .getPublicUrl(data.path)

  return urlData.publicUrl
}

function sqlString(value) {
  return `'${String(value).replaceAll("'", "''")}'`
}

async function main() {
  const { data: buckets, error: bucketsError } = await newClient.storage.listBuckets()
  if (bucketsError) throw bucketsError

  if (!buckets?.some((item) => item.id === bucket)) {
    throw new Error(`Destination bucket "${bucket}" does not exist in the new project`)
  }

  const { data: flavors, error } = await oldClient
    .from('flavors')
    .select('id,name,image,imageThumb')
    .order('createdAt', { ascending: true })

  if (error) throw error

  const sql = [
    '-- Generated by scripts/migrate-flavor-images-optimized.mjs',
    '-- Review before running in the new Supabase SQL Editor.',
    '',
  ]

  let migrated = 0
  let skipped = 0
  let failed = 0

  for (const flavor of flavors || []) {
    if (!flavor.image || flavor.image.startsWith('/')) {
      skipped += 1
      console.log(`[skip] ${flavor.id} ${flavor.name} uses local image: ${flavor.image}`)
      continue
    }

    try {
      const source = await downloadFlavorImage(flavor.image)
      const { full, thumb } = await createVariants(source)
      const safeId = String(flavor.id).replace(/[^a-zA-Z0-9_-]/g, '-')
      const stamp = Date.now()
      const fullPath = `flavors/${safeId}-${stamp}.webp`
      const thumbPath = `flavors/thumbs/${safeId}-${stamp}.webp`
      const image = await upload(fullPath, full)
      const imageThumb = await upload(thumbPath, thumb)

      sql.push(
        `UPDATE happycheese.flavors SET image = ${sqlString(image)}, "imageThumb" = ${sqlString(imageThumb)}, "updatedAt" = now() WHERE id = ${sqlString(flavor.id)};`
      )

      if (applyDbUpdates) {
        const { error: updateError } = await newClient
          .from('flavors')
          .update({ image, imageThumb, updatedAt: new Date().toISOString() })
          .eq('id', flavor.id)

        if (updateError) throw updateError
      }

      migrated += 1
      console.log(`[ok] ${flavor.id} ${flavor.name}`)
    } catch (error) {
      failed += 1
      console.error(`[fail] ${flavor.id} ${flavor.name}: ${error.message}`)
    }
  }

  await mkdir('migration-output', { recursive: true })
  await writeFile('migration-output/flavor-image-updates.sql', `${sql.join('\n')}\n`)

  console.log(JSON.stringify({
    migrated,
    skipped,
    failed,
    applyDbUpdates,
    sqlFile: 'migration-output/flavor-image-updates.sql',
  }, null, 2))
}

main().catch((error) => {
  console.error(error)
  process.exit(1)
})
